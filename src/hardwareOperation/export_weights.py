"""Export DenseCfC weights as per-channel INT8 C header files.

Generates ``weights.h`` with quantized weight arrays, per-channel scales,
FP32 biases, and dimension macros.  Also generates ``normalization.h`` with
mu-law center/scale/mu constants for the C inference pipeline.

Usage::

    python -m src.hardwareOperation.export_weights \\
        --checkpoint log/.../S1_dense_cfc_head_ft.pt \\
        --output-dir src/hardwareOperation
"""

from __future__ import annotations

import argparse
import json
import sys
import types
from pathlib import Path
from typing import Any

import numpy as np
import torch

